-- Per-table counters written by every stage; the reconciliation view derives `closes` from them (§7).
CREATE TABLE IF NOT EXISTS mig.run_ledger (
    run_id          VARCHAR(64)     NOT NULL,
    namespace       VARCHAR(32)     NOT NULL,
    table_name      VARCHAR(128)    NOT NULL,
    table_order     INTEGER         NOT NULL,
    table_role      VARCHAR(16)     NOT NULL,
    extracted       BIGINT          NULL,   -- EXTRACT: rows written to fixed-width files
    extract_files   INTEGER         NULL,   -- EXTRACT: files (= key ranges) written
    loaded          BIGINT          NULL,   -- LOAD: rows inserted into stg
    rejected        BIGINT          NULL,   -- LOAD: rows written to mig.rejects with stage LOAD
    validated       BIGINT          NULL,   -- VALIDATE: rows with status VALIDATED (purge-safe for data tables)
    validate_failed BIGINT          NULL,   -- VALIDATE: rows with status FAILED
    purge_intended  BIGINT          NULL,   -- PURGE: purge-safe keys selected for deletion
    purged          BIGINT          NULL,   -- PURGE: keys deleted and committed in Db2 (0 on dry run)
    purge_dry_run   BOOLEAN         NULL,
    updated_at      TIMESTAMP(3)    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT pk_run_ledger PRIMARY KEY (run_id, namespace, table_name),
    CONSTRAINT fk_run_ledger_runs FOREIGN KEY (run_id, namespace) REFERENCES mig.runs (run_id, namespace),
    CONSTRAINT ck_run_ledger_role CHECK (table_role IN ('data', 'reference'))
);

-- Every stage attempt on every host; the migration transcript is rendered from this table.
CREATE TABLE IF NOT EXISTS mig.stage_log (
    stage_log_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id          VARCHAR(64)     NOT NULL,
    namespace       VARCHAR(32)     NOT NULL,
    stage           VARCHAR(16)     NOT NULL,
    table_name      VARCHAR(128)    NULL,   -- NULL = the stage as a whole
    host            VARCHAR(8)      NOT NULL,
    attempt         INTEGER         NOT NULL,
    status          VARCHAR(16)     NOT NULL,
    rows_processed  BIGINT          NULL,
    started_at      TIMESTAMP(3)    NOT NULL,
    finished_at     TIMESTAMP(3)    NULL,
    message         VARCHAR(4000)   NULL,
    CONSTRAINT pk_stage_log PRIMARY KEY (stage_log_id),
    CONSTRAINT ck_stage_log_stage CHECK (stage IN ('INIT', 'EXTRACT', 'LOAD', 'VALIDATE', 'PURGE', 'RECONCILE')),
    CONSTRAINT ck_stage_log_host CHECK (host IN ('eks', 'aca', 'local')),
    CONSTRAINT ck_stage_log_status CHECK (status IN ('RUNNING', 'OK', 'FAILED'))
);
CREATE INDEX IF NOT EXISTS ix_stage_log_run ON mig.stage_log (run_id, namespace, stage);
