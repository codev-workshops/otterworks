-- Failed source rows are retained here with their raw bytes (§6); never deleted by PURGE.
CREATE TABLE IF NOT EXISTS mig.rejects (
    reject_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id          VARCHAR(64)     NOT NULL,
    namespace       VARCHAR(32)     NOT NULL,
    table_name      VARCHAR(128)    NOT NULL,
    source_key      VARCHAR(64) COLLATE "C"     NOT NULL,   -- canonical key text, trailing spaces preserved
    stage           VARCHAR(16)     NOT NULL,
    rule_name       VARCHAR(64)     NOT NULL,
    field           VARCHAR(128)    NULL,
    sqlstate        CHAR(5)         NULL,
    native_error    INTEGER         NULL,
    error           VARCHAR(4000)   NOT NULL,
    raw_bytes       BYTEA           NULL,       -- LOAD: the full fixed-width record
    field_bytes     BYTEA           NULL,       -- LOAD: raw bytes of the failing field
    range_seq       INTEGER         NULL,
    batch_id        INTEGER         NULL,
    created_at      TIMESTAMP(3)    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT pk_rejects PRIMARY KEY (reject_id),
    CONSTRAINT uq_rejects_key UNIQUE (run_id, namespace, table_name, source_key),
    CONSTRAINT fk_rejects_runs FOREIGN KEY (run_id, namespace) REFERENCES mig.runs (run_id, namespace),
    CONSTRAINT ck_rejects_stage CHECK (stage IN ('LOAD', 'VALIDATE'))
);
